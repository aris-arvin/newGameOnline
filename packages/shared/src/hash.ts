/**
 * Deterministic serialization + hashing, used to fingerprint simulation state
 * and event streams for replay/determinism checks (design prompt §10.12, §18.6).
 */

/** Canonical JSON: object keys sorted, no incidental whitespace. */
export function stableStringify(value: unknown): string {
  if (value === null || typeof value !== 'object') {
    return JSON.stringify(value) ?? 'null';
  }
  if (Array.isArray(value)) {
    return `[${value.map(stableStringify).join(',')}]`;
  }
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(obj[k])}`).join(',')}}`;
}

/** FNV-1a 32-bit hash of a string, as an 8-char hex string. */
export function hashString(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return (h >>> 0).toString(16).padStart(8, '0');
}

/** Stable hash of any JSON-serialisable value. */
export function hashValue(value: unknown): string {
  return hashString(stableStringify(value));
}
